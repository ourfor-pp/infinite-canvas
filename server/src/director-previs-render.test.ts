import { createHash } from "node:crypto";
import assert from "node:assert/strict";
import { after, test } from "node:test";
import { mkdtempSync, readFileSync, writeFileSync, mkdirSync, rmSync } from "node:fs";
import { tmpdir } from "node:os";
import { dirname, join } from "node:path";
import { execFileSync } from "node:child_process";
const temp = mkdtempSync(join(tmpdir(), "previs-render-test-"));
process.env.DATA_DIR = temp; process.env.AUTH_MODE = "dev";
const { db } = await import("./database.js");
const workspace = await import("./director-workspace.js");
const render = await import("./director-previs-render.js");
const previs = await import("./director-previs.js");
const userId = "previs-user", projectId = "previs-render";
after(() => { db.close(); rmSync(temp, { recursive: true, force: true }); });
async function terminal(id: string) {
    for (let i = 0; i < 600; i++) { const job = render.getPrevisRender(userId, projectId, id); if (!["queued", "running"].includes(job.status)) return job; await new Promise((resolve) => setTimeout(resolve, 100)); }
    throw new Error("预演导出未在 60 秒内完成");
}
test("独立进程导出、取消、失败重试、重启恢复与范围版本校验", async () => {
    const now = new Date().toISOString();
    db.prepare("INSERT INTO users(id,username,is_admin,created_at,updated_at) VALUES(?,?,1,?,?)").run(userId, userId, now, now);
    db.prepare("INSERT INTO projects(id,user_id,kind,title,payload,revision,created_at,updated_at) VALUES(?,?,'director','预演回归','{}',1,?,?)").run(projectId, userId, now, now);
    const root = workspace.ensureDirectorProjectWorkspace(userId, projectId);
    const fixture = JSON.parse(readFileSync(new URL("./agent/scenes/director/skills/director-stage-previs/references/example.json", import.meta.url), "utf8"));
    const folder = join(root, "scenes/station/segments/meeting"); mkdirSync(folder, { recursive: true });
    writeFileSync(join(folder, "../../scene.json"), JSON.stringify(fixture.scene));
    writeFileSync(join(folder, "segment.md"), "---\nid: meeting\nkind: segment-design\nsequenceId: station\nname: 交接\norder: 1\nestimatedSeconds: 24\n---\n相遇与交接\n");
    writeFileSync(join(folder, "previs.json"), JSON.stringify(fixture.plan));
    workspace.reconcileDirectorProjectFiles(userId, projectId);
    const state = previs.readDirectorPrevis(userId, projectId, "meeting");
    const job = render.createPrevisRender(userId, projectId, "meeting", { expectedHash: state.hash, start: 11.5, end: 12.5 });
    render.cancelPrevisRender(userId, projectId, job.id);
    assert.equal(render.getPrevisRender(userId, projectId, job.id).status, "cancelled");
    render.retryPrevisRender(userId, projectId, job.id);
    const ready = await terminal(job.id); assert.equal(ready.status, "succeeded", ready.error || "");
    assert.equal(ready.result.frames, 24);
    const probe = JSON.parse(execFileSync("ffprobe", ["-v", "error", "-show_streams", "-of", "json", join(root, ready.result.path)], { encoding: "utf8" }));
    assert.equal(probe.streams.length, 1); assert.equal(probe.streams[0].codec_type, "video"); assert.equal(probe.streams[0].r_frame_rate, "24/1");
    const payload = { durationSeconds: 1, segmentRanges: [{ segmentId: "meeting", start: 11.5, end: 12.5 }], videoReferences: [{ path: ready.result.path, purpose: "交接调度", includeAudio: false, segmentId: "meeting", sourceHash: state.hash, start: 11.5, end: 12.5 }] };
    assert.equal(previs.getTaskPrevisInputs(userId, projectId, payload).files.length, 1);
    const bytes = readFileSync(join(root, ready.result.path)); writeFileSync(join(root, ready.result.path), "changed");
    assert.throws(() => previs.getTaskPrevisInputs(userId, projectId, payload), /导出记录/);
    writeFileSync(join(root, ready.result.path), bytes);
    const failed = render.createPrevisRender(userId, projectId, "meeting", { expectedHash: state.hash, start: 0, end: 1 });
    const original = (db.prepare("SELECT snapshot FROM director_previs_renders WHERE id=?").get(failed.id) as { snapshot: string }).snapshot;
    db.prepare("UPDATE director_previs_renders SET snapshot=? WHERE id=?").run(JSON.stringify({ ...JSON.parse(original), output: "../outside.mp4" }), failed.id);
    assert.equal((await terminal(failed.id)).status, "failed");
    db.prepare("UPDATE director_previs_renders SET snapshot=?, status='running' WHERE id=?").run(original, failed.id);
    render.resumePrevisRenders();
    assert.equal((await terminal(failed.id)).status, "succeeded");
    const frame = previs.createDirectorLookFrame(userId, projectId, "meeting", 12, state.hash);
    const capture = render.createPrevisRender(userId, projectId, "meeting", { expectedHash: state.hash, kind: "frame", frameId: frame.id, start: 12 });
    assert.equal((await terminal(capture.id)).status, "succeeded");
    assert.ok(readFileSync(join(root, frame.path, "inputs/previs.png")).length > 1000);
    const receipt = JSON.parse(readFileSync(join(root, frame.path, "inputs/capture.json"), "utf8"));
    assert.equal(receipt.sourceHash, state.hash); assert.equal(receipt.time, 12);
    const { createDirectorLookFrameGeneration } = await import("./director-look-frame.js");
    const promptHash = createHash("sha256").update(readFileSync(join(root, frame.path, "prompt.md"))).digest("hex");
    const generate = () => createDirectorLookFrameGeneration(userId, projectId, { segmentId: "meeting", frameId: frame.id, expectedHash: promptHash });
    assert.throws(generate, /请先编写/);
    const oldCapture = render.createPrevisRender(userId, projectId, "meeting", { expectedHash: state.hash, kind: "frame", frameId: frame.id, start: 12 });
    previs.createDirectorLookFrame(userId, projectId, "meeting", 12, state.hash, frame.id);
    assert.throws(generate, /尚未提取完成/);
    assert.equal((await terminal(oldCapture.id)).status, "failed", "旧提取不得覆盖新一次请求");
    assert.throws(() => previs.createDirectorLookFrame(userId, projectId, "meeting", 13, state.hash, frame.id), /时间锚点不能修改/);
    assert.throws(() => render.createPrevisRender(userId, projectId, "meeting", { expectedHash: "stale" }), /预演已经修改/);
    assert.throws(() => render.getPrevisRender("another-user", projectId, job.id), /不存在/);
});

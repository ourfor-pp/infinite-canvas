import assert from "node:assert/strict";
import { after, test } from "node:test";
import { mkdtempSync, rmSync, writeFileSync } from "node:fs";
import { tmpdir } from "node:os";
import { join } from "node:path";
import { audioDefaults } from "./audio-contract.js";
const root = mkdtempSync(join(tmpdir(), "audio-canvas-"));
process.env.DATA_DIR = root;
process.env.APP_SECRET = "audio-contract-test";
const { db } = await import("./database.js");
const { saveMediaExecutorSettings, refreshMediaExecutorCatalog } = await import("./media-executor-settings.js");
const { listPublicModels } = await import("./provider-service.js");
const { validateGenerationRequest } = await import("./generation-service.js");
const { prepareExecutorRequest } = await import("./media-capabilities.js");
const { storeLocalFile } = await import("./file-store.js");
saveMediaExecutorSettings({ url: "http://executor.test", token: "test" });
after(() => { db.close(); rmSync(root, { recursive: true, force: true }); });
test("公开目录和后端校验使用同一音频定义", async (t) => {
    const id = "qwen3-tts-1.7b-customvoice-local";
    t.mock.method(globalThis, "fetch", async () => Response.json({ protocolVersion: "2", models: { [id]: true }, comfyFeatures: {} }));
    await refreshMediaExecutorCatalog();
    const model = listPublicModels().find((item) => item.id === id)!;
    assert.ok(model?.audioContract);
    const request = { kind: "audio" as const, audioInputVersion: 1 as const, model: model.value, prompt: "你好", mode: "speech", operation: "generate", params: audioDefaults(model.audioContract!) };
    assert.doesNotThrow(() => validateGenerationRequest("user", request));
    assert.throws(() => validateGenerationRequest("user", { ...request, params: { voice: "alloy" } }), /不支持的参数/);
    assert.throws(() => validateGenerationRequest("user", { ...request, mode: "music" }), /模式与模型/);
});
test("参考用途和文字传到执行器，Music3 空歌词映射为纯音乐", async (t) => {
    const now = new Date().toISOString();
    db.prepare("INSERT INTO users(id,username,created_at,updated_at) VALUES('audio-user','audio-user',?,?)").run(now, now);
    const path = join(root, "reference.wav");
    writeFileSync(path, "audio fixture");
    const file = storeLocalFile("audio-user", path, "reference.wav", "audio/wav");
    t.mock.method(globalThis, "fetch", async () => Response.json({ id: "uploaded.wav" }));
    const result = await prepareExecutorRequest("audio-user", "clone", "qwen3-tts-1.7b-base-local", { kind: "audio", audioInputVersion: 1, mode: "speech", operation: "clone", prompt: "你好", references: [{ fileId: file.id, kind: "audio", role: "reference", transcript: "参考台词" }] });
    assert.equal(result.references[0].transcript, "参考台词");
    assert.equal(result.references[0].role, "reference");
    assert.equal(result.operation, "clone");
    const music = await prepareExecutorRequest("audio-user", "music", "minimax-music3-local", { kind: "audio", audioInputVersion: 1, mode: "music", operation: "generate", prompt: "安静钢琴", params: { lyrics: "" } });
    assert.equal(music.params.lyrics, "[Instrumental]");
});

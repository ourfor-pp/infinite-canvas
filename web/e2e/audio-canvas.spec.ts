import { expect, test } from "@playwright/test";
import { execFileSync } from "node:child_process";
import { audioContractFor } from "../../server/src/audio-contract";

for (const theme of ["light", "dark"]) test(`音频模型参数与原地重生成 ${theme}`, async ({ page }, testInfo) => {
    const audio = execFileSync("ffmpeg", ["-v", "error", "-f", "lavfi", "-i", "sine=frequency=440:duration=0.1", "-f", "wav", "pipe:1"]);
    const requests: any[] = [];
    let fail = false;
    await page.route(/^https?:\/\/[^/]+\/api\//, async (route) => {
        const req = route.request();
        const path = new URL(req.url()).pathname;
        if (path.endsWith("/content")) return route.fulfill({ contentType: "audio/wav", body: audio });
        let data: unknown = [];
        if (path === "/api/generations" && req.method() === "POST") { requests.push(req.postDataJSON()); data = { id: `audio-${requests.length}` }; }
        else if (/\/generations\/audio-/.test(path)) data = { id: `audio-${requests.length}`, status: fail ? "failed" : "succeeded", error: "测试失败", result: { files: [{ fileId: `result-${requests.length}`, mimeType: "audio/wav", bytes: audio.length }] } };
        else if (path.includes("/files/")) data = { fileId: path.split("/").at(-1), mimeType: "audio/wav", bytes: audio.length };
        else if (path === "/api/agent/config") data = { ready: false, protocolVersion: 4, storageVersion: 2 };
        else if (path.endsWith("/capabilities")) data = { sceneId: "canvas", engines: [], skills: [], referenceKinds: ["canvas"], composer: { suggestions: [] } };
        else if (path.endsWith("/conversation")) data = { sessions: [], session: null, queuedMessages: [] };
        else if (req.method() === "PUT") data = { ...req.postDataJSON(), id: "canvas-e2e", revision: 2 };
        await route.fulfill({ json: { data } });
    });
    await page.setViewportSize({ width: 1440, height: 1080 });
    await page.goto(`/__canvas-test.html?theme=${theme}`);
    await page.addStyleTag({ content: "#root > .ant-app { height: 100%; }" });
    const models = [["qwen3-tts-1.7b-customvoice-local", "自定义音色"], ["qwen3-tts-1.7b-base-local", "声音克隆"], ["qwen3-tts-1.7b-voicedesign-local", "音色设计"], ["minimax-music3-local", "音乐模型"], ["indextts-2.5-local", "IndexTTS"]].map(([id, name]) => ({ id, name, value: `p::${id}`, providerId: "p", providerName: "测试", output: "audio", inputs: ["text", "audio"], enabled: true, audioContract: audioContractFor({ id }) }));
    await page.evaluate(async (models) => {
        const path = "/src/stores/use-config-store.ts";
        const { useConfigStore } = await import(/* @vite-ignore */ path);
        useConfigStore.getState().hydrateModels(models, { audio: models[0].value });
    }, models);
    await page.getByRole("button", { name: "音频", exact: true }).click();
    const node = page.locator('[data-node-id^="audio-"]');
    await node.dblclick({ position: { x: 50, y: 50 } });
    const panel = page.locator("[data-canvas-node-panel]");
    await expect(panel.getByLabel("音色", { exact: true })).toHaveValue("Vivian");
    const prompt = panel.locator('[contenteditable="true"]');
    await prompt.fill("你好，欢迎来到画布。");
    const generate = panel.getByRole("button", { name: "开始生成", exact: true });
    await page.screenshot({ path: testInfo.outputPath(`audio-${theme}.png`) });
    await generate.click();
    await expect(node.locator("audio")).toHaveAttribute("src", /result-1/);
    expect(requests[0]).toMatchObject({ audioInputVersion: 1, mode: "speech", operation: "generate", params: { speaker: "Vivian", language: "Auto" }, references: [] });
    expect(requests[0].params).not.toHaveProperty("voice");
    fail = true;
    await prompt.fill("重做这段声音。");
    await generate.click();
    await expect(page.locator(".ant-message-error")).toContainText("测试失败");
    await expect(node.locator("audio")).toHaveAttribute("src", /result-1/);
    await expect(page.locator("[data-node-id]")).toHaveCount(1);
    fail = false;
    await generate.click();
    await expect(node.locator("audio")).toHaveAttribute("src", /result-3/);
    const picker = panel.getByRole("combobox").filter({ hasNot: page.locator("option") }).first();
    await picker.click();
    await page.getByRole("option", { name: /音乐模型/ }).click();
    await expect(panel.getByLabel("歌词（留空生成纯音乐）")).toBeVisible();
    await expect(panel.getByLabel("音色", { exact: true })).toHaveCount(0);
    await generate.click();
    await expect(node.locator("audio")).toHaveAttribute("src", /result-4/);
    expect(requests[3]).toMatchObject({ mode: "music", params: { seconds: 30, lyrics: "" } });
    expect(requests[3].params).not.toHaveProperty("speaker");
    await expect(page.locator("[data-node-id]")).toHaveCount(1);
    await picker.click();
    await page.getByRole("option", { name: /声音克隆/ }).click();
    await expect(generate).toBeDisabled();
    await expect(panel.getByText("请添加音色参考", { exact: true })).toBeVisible();
    await picker.click();
    await page.getByRole("option", { name: /音色设计/ }).click();
    await expect(generate).toBeDisabled();
    await panel.getByLabel("音色描述", { exact: true }).fill("温柔清晰的女声");
    await expect(generate).toBeEnabled();
    await page.evaluate(async () => {
        const path = "/src/stores/canvas/use-canvas-store.ts";
        const { useCanvasStore } = await import(/* @vite-ignore */ path);
        const project = useCanvasStore.getState().projects[0];
        const nodes = ["voice-ref", "emotion-ref", "clone-target"].map((id, index) => ({ id, type: "audio", title: id, position: { x: 150 + index * 350, y: 100 }, width: 300, height: 110, metadata: { content: index < 2 ? `/api/files/${id}/content` : undefined, storageKey: index < 2 ? `server:${id}` : undefined, mimeType: "audio/wav", durationMs: 100, prompt: "使用参考声音朗读这句话。", model: "p::indextts-2.5-local" } }));
        const connections = ["voice-ref", "emotion-ref"].map((id) => ({ id: `edge-${id}`, fromNodeId: id, toNodeId: "clone-target", fromPortId: "output", toPortId: "input" }));
        window.dispatchEvent(new CustomEvent("infinite-canvas:project-updated", { detail: { ...project, nodes, connections, viewport: { x: 0, y: 0, k: 0.7 } } }));
    });
    const clone = page.locator('[data-node-id="clone-target"]');
    await clone.dblclick({ position: { x: 50, y: 50 } });
    await expect(generate).toBeDisabled();
    await panel.getByLabel("emotion-ref用途").selectOption("emotion");
    await panel.getByLabel("情绪强度").fill("0.6");
    await generate.click();
    await expect(clone.locator('audio[src*="result-5"]')).toHaveCount(1);
    expect(requests[4].references).toEqual(expect.arrayContaining([{ fileId: "voice-ref", kind: "audio", role: "reference" }, { fileId: "emotion-ref", kind: "audio", role: "emotion" }]));
    expect(requests[4].params.emotionStrength).toBe(0.6);
    await expect(page.locator("[data-node-id]")).toHaveCount(3);
});

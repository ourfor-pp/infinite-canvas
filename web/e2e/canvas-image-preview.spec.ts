import { expect, test } from "@playwright/test";

for (const theme of ["light", "dark"]) test(`图片节点大图支持缩放拖动且不影响画布 ${theme}`, async ({ page }) => {
    await page.setViewportSize({ width: 1440, height: 960 });
    await page.route(/^https?:\/\/[^/]+\/api\//, async route => {
        const request = route.request(), path = new URL(request.url()).pathname;
        if (path.endsWith("/content")) return route.fulfill({ contentType: "image/svg+xml", body: '<svg xmlns="http://www.w3.org/2000/svg" width="1200" height="600"><rect width="1200" height="600" fill="#ccd9e8"/><circle cx="600" cy="300" r="160" fill="#526b8c"/></svg>' });
        let data: unknown = request.method() === "PUT" ? { ...request.postDataJSON(), revision: request.postDataJSON().revision + 1 } : [];
        if (path === "/api/files" && request.method() === "POST") data = { fileId: "preview", url: "/api/files/preview/content", bytes: 240, mimeType: "image/svg+xml" };
        else if (path === "/api/agent/config") data = { ready: false, protocolVersion: 4, storageVersion: 2 };
        else if (path.endsWith("/capabilities")) data = { sceneId: "canvas", engines: [], skills: [], referenceKinds: ["canvas"], composer: { suggestions: [] } };
        else if (path.endsWith("/conversation")) data = { sessions: [], session: null, queuedMessages: [] };
        await route.fulfill({ json: { data } });
    });
    await page.goto(`/__canvas-test.html?theme=${theme}`);
    await page.addStyleTag({ content: "#root > .ant-app { height: 100% }" });
    const transfer = await page.evaluateHandle(() => {
        const data = new DataTransfer();
        data.items.add(new File(['<svg xmlns="http://www.w3.org/2000/svg" width="1200" height="600"/>'], "预览测试.svg", { type: "image/svg+xml" }));
        return data;
    });
    await page.locator("div.relative.h-full.w-full.select-none.overflow-hidden").dispatchEvent("drop", { dataTransfer: transfer, clientX: 750, clientY: 430 });
    const node = page.locator('[data-node-id^="image-"]');
    await expect(node.locator("img")).toBeVisible();
    await node.click({ position: { x: 30, y: 30 } });
    const panel = page.locator("[data-canvas-node-panel]");
    await expect(panel.getByText("调整图片", { exact: true })).toHaveCount(0);
    await expect(panel.getByText("修改只影响下一次生成", { exact: true })).toHaveCount(0);
    const prompt = panel.locator('[contenteditable="true"]');
    await expect(prompt).toHaveCSS("height", "112px");
    await prompt.fill("换成男生");
    await page.screenshot({ path: `../.tmp/canvas-compact-image-editor-${theme}.png` });
    await prompt.fill(Array.from({ length: 20 }, (_, index) => `第${index + 1}条画面要求`).join("\n"));
    expect(await prompt.evaluate(element => element.scrollHeight > element.clientHeight)).toBe(true);
    await prompt.evaluate(element => { element.scrollTop = element.scrollHeight; });
    expect(await prompt.evaluate(element => element.scrollTop)).toBeGreaterThan(0);
    await prompt.fill("换成男生");
    const canvasState = () => node.evaluate(element => ({ nodeStyle: element.getAttribute("style"), viewport: element.closest(".origin-top-left")?.getAttribute("style") }));
    const before = await canvasState();
    await page.getByRole("button", { name: "查看图片详情", exact: true }).click();
    const image = page.locator(".ant-image-preview img");
    await expect(image).toBeVisible();
    await expect(page.locator(".ant-image-preview-mask")).toHaveCSS("backdrop-filter", "blur(8px)");
    await expect(page.locator(".ant-image-preview-mask")).toHaveCSS("background-color", "rgba(0, 0, 0, 0.72)");
    const initial = await image.evaluate(element => getComputedStyle(element).transform);
    await image.hover();
    await page.mouse.wheel(0, -250);
    await expect.poll(() => image.evaluate(element => getComputedStyle(element).transform)).not.toBe(initial);
    const zoomed = await image.evaluate(element => getComputedStyle(element).transform);
    await page.mouse.move(700, 450);
    await page.mouse.down();
    await page.mouse.move(820, 500, { steps: 10 });
    await page.mouse.up();
    await expect.poll(() => image.evaluate(element => getComputedStyle(element).transform)).not.toBe(zoomed);
    await page.screenshot({ path: `../.tmp/canvas-image-preview-${theme}.png` });
    await page.keyboard.press("Escape");
    await expect(image).toBeHidden();
    expect(await canvasState()).toEqual(before);
    await page.getByRole("button", { name: "放大预览", exact: true }).click();
    await expect(image).toBeVisible();
    await page.locator(".ant-image-preview-close").click();
    await expect(image).toBeHidden();
    expect(await canvasState()).toEqual(before);
});

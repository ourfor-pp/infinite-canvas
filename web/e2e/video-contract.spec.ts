import { expect, test } from "@playwright/test";
import { execFileSync } from "node:child_process";
import { videoContractFor } from "../../server/src/video-contract";
for (const theme of ["light", "dark"]) test(`视频模型参数切换和原地重生成 ${theme}`, async ({ page }, testInfo) => {
    const video = execFileSync("ffmpeg", ["-v", "error", "-f", "lavfi", "-i", "color=blue:s=160x96:d=0.1", "-c:v", "libx264", "-movflags", "frag_keyframe+empty_moov", "-f", "mp4", "pipe:1"]);
    const requests: any[] = []; let fail = false;
    await page.route(/^https?:\/\/[^/]+\/api\//, async (route) => {
        const req = route.request(), path = new URL(req.url()).pathname;
        if (path.endsWith("/content")) return route.fulfill({ contentType: "video/mp4", body: video });
        let data: unknown = [];
        if (path === "/api/generations" && req.method() === "POST") { requests.push(req.postDataJSON()); data = { id: `video-${requests.length}` }; }
        else if (/\/generations\/video-/.test(path)) data = { id: `video-${requests.length}`, status: fail ? "failed" : "succeeded", error: "测试失败", result: { files: [{ fileId: `result-${requests.length}`, mimeType: "video/mp4", bytes: video.length }] } };
        else if (path.includes("/files/")) data = { fileId: path.split("/").at(-1), mimeType: "video/mp4", bytes: video.length };
        else if (path === "/api/agent/config") data = { ready: false, protocolVersion: 4, storageVersion: 2 };
        else if (path.endsWith("/capabilities")) data = { sceneId: "canvas", engines: [], skills: [], referenceKinds: ["canvas"], composer: { suggestions: [] } };
        else if (path.endsWith("/conversation")) data = { sessions: [], session: null, queuedMessages: [] };
        else if (req.method() === "PUT") data = { ...req.postDataJSON(), id: "canvas-e2e", revision: 2 };
        await route.fulfill({ json: { data } });
    });
    await page.setViewportSize({ width: 1440, height: 1080 });
    await page.goto(`/__canvas-test.html?theme=${theme}`);
    await page.addStyleTag({ content: "#root > .ant-app { height:100% }" });
    const models = [["minimax-h3-ref2va-local", "H3 多参考", ""], ["minimax-h3-fl2va-local", "H3 首尾帧", ""], ["sora-2", "OpenAI 视频", "openai-video"]].map(([id, name, endpoint]) => ({ id, name, value: `p::${id}`, providerId: "p", providerName: "测试", output: "video", inputs: ["text", "image", "video", "audio"], enabled: true, videoContract: videoContractFor({ id, endpoint }) }));
    await page.evaluate(async models => {
        const path = "/src/stores/use-config-store.ts";
        const { useConfigStore } = await import(/* @vite-ignore */ path);
        useConfigStore.getState().hydrateModels(models, { video: models[0].value });
    }, models);
    await page.getByRole("button", { name: "视频", exact: true }).click();
    const node = page.locator('[data-node-id^="video-"]');
    await node.dblclick({ position: { x: 50, y: 50 } });
    const panel = page.locator("[data-canvas-node-panel]");
    const prompt = panel.locator('[contenteditable="true"]');
    await prompt.fill("一只茶杯缓慢转动");
    const settings = panel.getByRole("button").filter({ has: page.locator("svg.lucide-settings-2") });
    await settings.click();
    await expect(page.getByLabel("分辨率", { exact: true })).toHaveValue("480p");
    await page.getByLabel("时长", { exact: true }).selectOption("5");
    await page.getByLabel("画面比例", { exact: true }).selectOption("9:16");
    await page.screenshot({ path: testInfo.outputPath(`video-${theme}.png`) });
    await settings.click();
    const generate = panel.getByRole("button", { name: "生成", exact: true });
    await generate.click();
    await expect(node.locator("video")).toHaveAttribute("src", /result-1/);
    expect(requests[0]).toMatchObject({ videoInputVersion: 1, params: { ratio: "9:16", seconds: 5, resolution: "480p" }, references: [] });
    fail = true;
    await prompt.fill("慢一点"); await generate.click();
    await expect(page.locator(".ant-message-error")).toContainText("测试失败");
    await expect(node.locator("video")).toHaveAttribute("src", /result-1/);
    await expect(page.locator("[data-node-id]")).toHaveCount(1);
    fail = false;
    await panel.getByRole("combobox").click(); await page.getByRole("option", { name: /H3 首尾帧/ }).click();
    await expect(generate).toBeDisabled(); await expect(panel).toContainText("需要首帧参考图");
    await panel.getByRole("combobox").click(); await page.getByRole("option", { name: /OpenAI 视频/ }).click();
    await settings.click();
    await expect(page.getByLabel("分辨率", { exact: true })).toHaveCount(0);
    await expect(page.getByLabel("输出尺寸", { exact: true })).toHaveValue("1280x720");
    await expect(page.getByLabel("时长", { exact: true })).toHaveValue("4");
    await settings.click(); await generate.click();
    await expect(node.locator("video")).toHaveAttribute("src", /result-3/);
    expect(requests[2].params).toEqual({ size: "1280x720", seconds: 4 });
});

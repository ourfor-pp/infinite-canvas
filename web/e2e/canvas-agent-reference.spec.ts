import { expect, test } from "@playwright/test";

for (const theme of ["light", "dark"]) test(`节点工具栏和右键引用到 Agent ${theme}`, async ({ page }, testInfo) => {
    let sends = 0;
    const session = { id: "s1", projectId: "canvas-e2e", engine: "builtin", title: "测试", status: "idle", eventSeq: 0, currentRunId: null, pendingDecision: null, createdAt: new Date().toISOString(), updatedAt: new Date().toISOString(), events: [{ sessionId: "s1", seq: 1, runId: "r1", kind: "user_text", createdAt: new Date().toISOString(), payload: { text: "@旧的很长节点名称请制作动画", content: { version: 1, segments: [{ type: "canvas", mentionId: "sent-ref", projectId: "canvas-e2e", nodeId: "pic-0", label: "旧的很长节点名称" }, { type: "text", text: "请制作动画" }] } } }] };
    await page.route(/^https?:\/\/[^/]+\/api\//, async route => {
        const req = route.request(), path = new URL(req.url()).pathname;
        if (path.endsWith("/content")) return route.fulfill({ contentType: "image/svg+xml", body: '<svg xmlns="http://www.w3.org/2000/svg" width="100" height="100"><rect width="100" height="100" fill="steelblue"/></svg>' });
        if (req.method() === "POST" && path.endsWith("/messages")) sends++;
        let data: unknown = [];
        if (path === "/api/agent/config") data = { ready: false, protocolVersion: 4, storageVersion: 2 };
        else if (path.endsWith("/capabilities")) data = { sceneId: "canvas", engines: [], skills: [], referenceKinds: ["canvas"], composer: { suggestions: [] } };
        else if (path.endsWith("/references")) data = [0, 1, 2].map(i => ({ key: `pic-${i}`, label: `图${i}`, detail: "image", segment: { type: "canvas", projectId: "canvas-e2e", nodeId: `pic-${i}`, label: `图${i}` } }));
        else if (path.endsWith("/conversation")) data = { sessions: [session], session, queuedMessages: [] };
        else if (req.method() === "PUT") data = { ...req.postDataJSON(), revision: 2 };
        await route.fulfill({ json: { data } });
    });
    await page.setViewportSize({ width: 1800, height: 960 });
    await page.addInitScript(() => localStorage.setItem("agent-drafts-by-project", JSON.stringify({ "canvas-e2e": "保留我的描述 " })));
    await page.goto(`/__canvas-test.html?theme=${theme}`);
    await page.addStyleTag({ content: "#root > .ant-app { height:100% }" });
    await page.evaluate(async () => {
        const path = "/src/stores/canvas/use-canvas-store.ts";
        const { useCanvasStore } = await import(/* @vite-ignore */ path);
        const agentPath = "/src/stores/use-agent-store.ts";
        const { useAgentStore } = await import(/* @vite-ignore */ agentPath);
        useAgentStore.setState({ panelOpen: {}, drafts: { "canvas-e2e": "保留我的描述 " } });
        const project = useCanvasStore.getState().projects[0];
        const nodes = [
            { id: "group", type: "group", title: "目标分组", position: { x: 750, y: 150 }, width: 360, height: 350 },
            ...[0, 1, 2].map(i => ({ id: `pic-${i}`, type: "image", title: `图${i}`, position: { x: 330 + i * 130, y: 200 }, width: 100, height: 100, metadata: { content: "/api/files/test-image/content", storageKey: "server:test-image", naturalWidth: 100, naturalHeight: 100 } })),
        ];
        window.dispatchEvent(new CustomEvent("infinite-canvas:project-updated", { detail: { ...project, nodes } }));
    });
    const nodes = page.locator('[data-node-id^="pic-"]');
    await expect(nodes).toHaveCount(3);
    await nodes.nth(0).click({ position: { x: 50, y: 50 } });
    await page.getByRole("button", { name: "引用到 Agent", exact: true }).click();
    const editor = page.locator(".agent-composer-editor");
    await expect(editor).toBeVisible();
    await expect(editor).toContainText("保留我的描述");
    await expect(editor).toContainText("@图片 1");
    await expect(editor).toBeFocused();
    await expect(editor.locator("[data-segment]")).toHaveCount(1);
    expect(await editor.locator("[data-segment]").evaluate(el => JSON.parse((el as HTMLElement).dataset.segment!))).toMatchObject({ type: "canvas", nodeId: "pic-0", projectId: "canvas-e2e" });
    await nodes.nth(1).click({ button: "right" });
    await page.getByRole("button", { name: "引用到 Agent", exact: true }).last().click();
    await expect(editor).toContainText("@图片 2");
    await expect(editor).toContainText("保留我的描述");
    await expect(editor.locator("[data-segment]")).toHaveCount(2);
    await expect(editor).toBeFocused();
    const group = page.locator('[data-node-id="group"]');
    await group.click({ button: "right", position: { x: 8, y: 150 } });
    await page.getByRole("button", { name: "引用到 Agent", exact: true }).last().click();
    await expect(editor).toContainText("@分组 1");
    await expect(editor.locator("[data-segment]")).toHaveCount(3);
    const sentReference = page.locator("[data-agent-sent-reference]");
    await expect(sentReference).toHaveText("@图片 1");
    await expect(sentReference.locator("img")).toBeVisible();
    await expect(page.locator(".agent-user-bubble")).toContainText("请制作动画");
    expect(await sentReference.evaluate(el => parseFloat(getComputedStyle(el).marginRight))).toBeGreaterThan(0);
    const first = editor.locator("[data-segment]").first();
    await expect(first.locator("img")).toBeVisible();
    const code = "图片 1";
    await expect(page.locator("[data-canvas-reference-code]")).toHaveCount(0);
    await expect(first).toContainText(code);
    await first.hover();
    await expect(page.locator("[data-agent-reference-preview]")).toContainText(code);
    await expect(page.locator("[data-agent-reference-preview] img")).toBeVisible();
    await expect.poll(() => page.evaluate(async () => { const path = "/src/stores/use-agent-store.ts"; const { useAgentStore } = await import(/* @vite-ignore */ path); return useAgentStore.getState().hoveredCanvasReference?.nodeId; })).toBe("pic-0");
    await page.screenshot({ path: testInfo.outputPath("agent-reference-preview.png") });
    await first.click();
    await expect.poll(() => page.evaluate(async () => { const path = "/src/stores/use-agent-store.ts"; const { useAgentStore } = await import(/* @vite-ignore */ path); return useAgentStore.getState().canvasContext?.snapshot.selectedNodeIds; })).toEqual(["pic-0"]);
    await expect(editor).toContainText("保留我的描述");
    await editor.focus();
    await editor.evaluate(el => { const range = document.createRange(); range.selectNodeContents(el); range.collapse(false); const selection = window.getSelection()!; selection.removeAllRanges(); selection.addRange(range); });
    await editor.pressSequentially(" @");
    const menu = page.locator(".agent-mention-menu");
    const candidate = menu.getByRole("button", { name: "@图片 2 图1", exact: true });
    await expect(candidate.locator("img")).toBeVisible();
    await candidate.hover();
    const preview = page.locator("[data-agent-reference-preview]");
    await expect(preview).toContainText("图片 2");
    await expect(preview.locator("img")).toBeVisible();
    await expect.poll(() => page.evaluate(async () => { const path = "/src/stores/use-agent-store.ts"; const { useAgentStore } = await import(/* @vite-ignore */ path); return useAgentStore.getState().hoveredCanvasReference?.nodeId; })).toBe("pic-1");
    await expect.poll(() => page.evaluate(async () => { const path = "/src/stores/use-agent-store.ts"; const { useAgentStore } = await import(/* @vite-ignore */ path); return useAgentStore.getState().canvasContext?.snapshot.selectedNodeIds; })).toEqual(["pic-0"]);
    const menuBox = (await menu.boundingBox())!, previewBox = (await preview.boundingBox())!;
    expect(previewBox.x >= menuBox.x + menuBox.width || previewBox.x + previewBox.width <= menuBox.x).toBe(true);
    await page.screenshot({ path: testInfo.outputPath("agent-candidate-preview.png") });
    await page.mouse.move(20, 20);
    await expect(preview).toHaveCount(0);
    await expect.poll(() => page.evaluate(async () => { const path = "/src/stores/use-agent-store.ts"; const { useAgentStore } = await import(/* @vite-ignore */ path); return useAgentStore.getState().hoveredCanvasReference; })).toBeNull();
    await candidate.click();
    await expect(menu).toHaveCount(0);
    await expect(editor.locator("[data-segment]")).toHaveCount(4);
    await expect(editor.locator("[data-segment]").filter({ hasText: "@图片 2" })).toHaveCount(2);
    expect(sends).toBe(0);
    await page.screenshot({ path: testInfo.outputPath("agent-node-references.png") });
});

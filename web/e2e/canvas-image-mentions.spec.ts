import { expect, test } from "@playwright/test";

for (const theme of ["light", "dark"]) test(`图片引用统一面板、分组选择与自动连线 ${theme}`, async ({ page }) => {
    await page.setViewportSize({ width: 1600, height: 1100 });
    let saved: any;
    let files = 0;
    await page.route(/^https?:\/\/[^/]+\/api\//, async route => {
        const request = route.request(), path = new URL(request.url()).pathname;
        if (path.endsWith("/content")) return route.fulfill({ contentType: "image/svg+xml", body: '<svg xmlns="http://www.w3.org/2000/svg" width="200" height="200"><rect width="200" height="200" fill="#a1b3ca"/><circle cx="100" cy="100" r="50" fill="#506580"/></svg>' });
        let data: unknown = [];
        if (path === "/api/projects/canvas-e2e" && request.method() === "PUT") { saved = request.postDataJSON(); data = { ...saved, revision: saved.revision + 1 }; }
        else if (path === "/api/files" && request.method() === "POST") data = { fileId: `ref-${++files}`, url: `/api/files/ref-${files}/content`, bytes: 200, mimeType: "image/svg+xml" };
        else if (path === "/api/agent/config") data = { ready: false, protocolVersion: 4, storageVersion: 2 };
        else if (path.endsWith("/capabilities")) data = { sceneId: "canvas", engines: [], skills: [], referenceKinds: ["canvas"], composer: { suggestions: [] } };
        else if (path.endsWith("/conversation")) data = { sessions: [], session: null, queuedMessages: [] };
        await route.fulfill({ json: { data } });
    });
    await page.goto(`/__canvas-test.html?theme=${theme}`);
    await page.addStyleTag({ content: "#root > .ant-app { height: 100% }" });
    const canvas = page.locator("div.relative.h-full.w-full.select-none.overflow-hidden");
    for (const name of ["角色参考", "场景参考"]) {
        const transfer = await page.evaluateHandle(name => {
            const data = new DataTransfer();
            data.items.add(new File(["image"], `${name}.svg`, { type: "image/svg+xml" }));
            return data;
        }, name);
        await canvas.dispatchEvent("drop", { dataTransfer: transfer, clientX: 500 + files * 250, clientY: 300 });
        await expect.poll(() => saved?.nodes?.length).toBe(files);
    }
    await page.getByRole("button", { name: "图片", exact: true }).click();
    await expect.poll(() => saved?.nodes?.length).toBe(3);
    const targetId = saved.nodes[2].id;
    const panel = page.locator("[data-canvas-node-panel]");
    const prompt = panel.getByRole("textbox");
    const shelf = panel.getByLabel("参考素材");
    await expect(prompt).toHaveCSS("border-top-width", "0px");
    await expect(shelf).toHaveCSS("border-top-width", "0px");
    await prompt.fill("@");
    const menu = page.locator("[data-canvas-resource-mention-menu]");
    await expect(menu.getByRole("button", { name: /场景参考/ })).toHaveCount(0);
    await menu.getByRole("button", { name: /图片.*展开/ }).hover();
    await expect(page.locator('[data-canvas-reference-group="image"]')).toHaveCount(0);
    await menu.getByRole("button", { name: /图片.*展开/ }).click();
    await menu.getByRole("button", { name: /图片.*收起/ }).click();
    await expect(page.locator('[data-canvas-reference-group="image"]')).toHaveCount(0);
    await menu.getByRole("button", { name: /图片.*展开/ }).click();
    await menu.getByRole("button", { name: /场景参考/ }).hover();
    const hoverPreview = page.locator("[data-canvas-reference-hover-preview]");
    await expect(hoverPreview.getByRole("img", { name: "场景参考.svg" })).toBeVisible();
    const rootBox = (await menu.boundingBox())!;
    const groupBox = (await page.locator('[data-canvas-reference-group="image"]').boundingBox())!;
    expect(groupBox.x).toBeGreaterThan(rootBox.x + rootBox.width - 5);
    expect(Math.abs(groupBox.y - rootBox.y)).toBeLessThan(3);
    expect((await hoverPreview.boundingBox())!.x).toBeGreaterThan(groupBox.x + groupBox.width - 5);
    await page.screenshot({ path: `../.tmp/canvas-image-mention-menu-${theme}.png`, animations: "disabled" });
    await menu.getByRole("button", { name: /场景参考/ }).click();
    await expect(prompt).toContainText("@图片1");
    await expect(prompt.locator("img")).toHaveCount(0);
    await expect(shelf.getByRole("img", { name: "@图片1", exact: true })).toBeVisible();
    await expect.poll(() => saved?.connections?.length).toBe(1);
    expect(saved.connections[0].toNodeId).toBe(targetId);
    expect(saved.connections[0].fromNodeId).toBe(saved.nodes[1].id);
    await prompt.press("End"); await prompt.pressSequentially("@");
    await expect(menu.getByRole("button", { name: /场景参考/ })).toBeVisible();
    await expect(menu.getByRole("button", { name: /角色参考/ })).toHaveCount(0);
    await menu.getByRole("button", { name: /图片.*展开/ }).click();
    await menu.getByRole("button", { name: /角色参考/ }).click();
    await expect(prompt).toContainText("@图片2");
    await expect.poll(() => saved?.connections?.length).toBe(2);
    await prompt.fill("前文 后文");
    await prompt.press("Home"); await prompt.press("ArrowRight"); await prompt.press("ArrowRight");
    await shelf.getByRole("img", { name: "@图片1", exact: true }).hover();
    await shelf.getByRole("button", { name: "插入@图片1", exact: true }).click();
    await expect(prompt).toHaveText(/前文@图片1.*后文/);
    await expect.poll(() => saved?.connections?.length).toBe(2);
    await shelf.getByRole("img", { name: "@图片2", exact: true }).hover();
    await shelf.getByRole("button", { name: "插入@图片2", exact: true }).click();
    await shelf.getByRole("img", { name: "@图片1", exact: true }).hover();
    await shelf.getByRole("button", { name: "移除@图片1", exact: true }).click();
    await expect.poll(() => saved?.connections?.length).toBe(1);
    expect(saved.nodes).toHaveLength(3);
    expect(saved.connections[0].fromNodeId).toBe(saved.nodes[0].id);
    await expect(prompt).toContainText("@图片1");
    await expect(prompt).not.toContainText("@图片2");
    await shelf.getByRole("img", { name: "@图片1", exact: true }).hover();
    await expect(shelf.getByRole("button", { name: "移除@图片1", exact: true })).toHaveCSS("opacity", "1");
    await expect(shelf.getByRole("button", { name: "插入@图片1", exact: true })).toHaveCSS("opacity", "1");
    await expect(shelf.getByRole("button", { name: "插入@图片1", exact: true })).toHaveCSS("color", "rgb(255, 255, 255)");
    await page.screenshot({ path: `../.tmp/canvas-image-mentions-${theme}.png`, animations: "disabled" });
});
